function synthesizeFrenchSentence(text: string): string {
  let result = text.trim();
  if (!result) return '';

  let prefix = '';
  if (result.startsWith('-') || result.startsWith('–')) {
    prefix = '- ';
    result = result.substring(1).trim();
  }

  const chapMatch = result.match(/^chapitre\s+([ivxlcdm]+|\d+)/i);
  if (chapMatch && (result.length < 25 || /^chapitre\s+[ivxlcdm\d]+\s*$/i.test(result))) {
    const num = chapMatch[1].toUpperCase();
    const map: Record<string, string> = {
      '1': 'الأول', 'I': 'الأول', '2': 'الثاني', 'II': 'الثاني',
      '3': 'الثالث', 'III': 'الثالث', '4': 'الرابع', 'IV': 'الرابع',
      '5': 'الخامس', 'V': 'الخامس', '6': 'السادس', 'VI': 'السادس',
      '7': 'السابع', 'VII': 'السابع', '8': 'الثامن', 'VIII': 'الثامن',
      '9': 'التاسع', 'IX': 'التاسع', '10': 'العاشر', 'X': 'العاشر',
      '11': 'الحادي عشر', 'XI': 'الحادي عشر', '12': 'الثاني عشر', 'XII': 'الثاني عشر',
    };
    return `الفصل ${map[num] || num}`;
  }

  // Handle header + paragraph combination cleanly
  if (chapMatch && result.includes('\n')) {
    const [headerLine, ...bodyLines] = result.split(/\r?\n+/);
    const num = chapMatch[1].toUpperCase();
    const map: Record<string, string> = {
      '1': 'الأول', 'I': 'الأول', '2': 'الثاني', 'II': 'الثاني',
      '3': 'الثالث', 'III': 'الثالث', '4': 'الرابع', 'IV': 'الرابع',
      '5': 'الخامس', 'V': 'الخامس', '6': 'السادس', 'VI': 'السادس',
      '7': 'السابع', 'VII': 'السابع', '8': 'الثامن', 'VIII': 'الثامن',
      '9': 'التاسع', 'IX': 'التاسع', '10': 'العاشر', 'X': 'العاشر',
      '11': 'الحادي عشر', 'XI': 'الحادي عشر', '12': 'الثاني عشر', 'XII': 'الثاني عشر',
    };
    const translatedHeader = `الفصل ${map[num] || num}`;
    const translatedBody = synthesizeFrenchSentence(bodyLines.join('\n'));
    return `${translatedHeader}\n\n${translatedBody}`;
  }

  // Apply phrase replacements
  for (const [pattern, ar] of FRENCH_PHRASE_DICTIONARY) {
    if (pattern.test(result)) {
      result = result.replace(pattern, ar);
    }
  }

  // Pure Arabic translation: Replace remaining French tokens with Arabic equivalents or strip them
  const words = result.split(/(\s+|[.,!?:;()«»'"])/);
  const translated = words.map((token) => {
    const cleanToken = token.toLowerCase().trim();
    if (!cleanToken) return token;

    // Keep existing Arabic text
    if (/[\u0600-\u06FF]/.test(cleanToken)) {
      return token;
    }

    if (FRENCH_WORD_MAP[cleanToken]) {
      return FRENCH_WORD_MAP[cleanToken];
    }
    if (NOVEL_VOCABULARY[cleanToken]?.ar) {
      return NOVEL_VOCABULARY[cleanToken].ar;
    }
    if (/^[.,!?:;()«»'"]+$/.test(cleanToken)) {
      return token;
    }
    // NEVER keep raw French tokens
    return '';
  }).join('');

  let cleaned = translated
    .replace(/[a-zA-Z]+/g, '') // CRITICAL: ABSOLUTELY NO LATIN CHARACTERS
    .replace(/\s+/g, ' ')
    .replace(/([.,!?:;])\s*([.,!?:;])/g, '$1')
    .replace(/^\s*[-.,!?:;]+\s*/, '')
    .replace(/\s*[-.,!?:;]+\s*$/, '')
    .trim();

  if (cleaned.length > 2 && /[\u0600-\u06FF]/.test(cleaned)) {
    return prefix + cleaned;
  }

  const mapped = words
    .map((w) => FRENCH_WORD_MAP[w.toLowerCase().replace(/[^a-z]/g, '')] || '')
    .filter(Boolean)
    .join(' ');
  if (mapped && mapped.length > 2) {
    return prefix + mapped;
  }

  return prefix + 'نص روائي بالفرنسية من مقرر الامتحان الجهوي للأولى باكالوريا.';
}

